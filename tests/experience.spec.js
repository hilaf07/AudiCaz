test('seis módulos, escenarios, filtros, ayuda, resolución, persistencia y CSV', async ({page}) => {
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await register(page);
  await expect(page.locator('.channel-card')).toHaveCount(6);
  await page.getByRole('button',{name:'¿Qué significa este indicador?'}).first().click();
  await expect(page.locator('.help-popover')).toContainText('Verde');
  await page.getByRole('button',{name:'Pausar simulación'}).click();
  await expect(page.locator('.stat').first()).toContainText('Monitoreo pausado');
  await nav(page,'Centro de alertas');
  await expect(page.getByRole('button',{name:'Simular problema'})).toBeDisabled();
  await page.getByRole('button',{name:'Iniciar simulación'}).click();
  for(const key of ['clipping','feedback','silence','vocal','loud']){
    await page.getByLabel('Tipo de problema').selectOption(key);
    await page.getByRole('button',{name:'Simular problema'}).click();
  }
  await expect(page.locator('.alert-item')).toHaveCount(7);
  await expect(page.locator('.alert-item').first()).toHaveClass(/critical/);
  await page.getByLabel('Filtrar por gravedad').selectOption('critical');
  await expect(page.locator('.alert-item')).toHaveCount(2);
  await page.getByRole('button',{name:'¿Cómo lo soluciono?',exact:true}).first().click();
  await expect(page.locator('.problem-guide').first()).toContainText('¿Cómo verificar el resultado?');
  await page.getByRole('button',{name:'Volver sin cambiar el estado'}).click();
  await page.getByRole('button',{name:/Resolver/}).first().click();
  await page.getByLabel('Filtrar por gravedad').selectOption('resolved');
  await expect(page.locator('.alert-item')).toHaveCount(1);
  await expect(page.locator('.alert-item')).toContainText('Solucionado');
  await nav(page,'Monitoreo de canales');
  await expect(page.locator('.channel-card')).toHaveCount(6);
  await page.locator('.channel-card').first().click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await nav(page,'Análisis de audio');
  await expect(page.locator('.spectrum-bars>div')).toHaveCount(64);
  await nav(page,'Recomendaciones');
  await expect(page.locator('.recommendation-card')).toHaveCount(6);
  await nav(page,'Historial');
  await expect(page.locator('tbody tr')).toHaveCount(7);
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Exportar CSV'}).click();
  expect((await download).suggestedFilename()).toBe('audicaz-historial.csv');
  await page.getByRole('button',{name:'Pausar simulación'}).click();
  await page.reload();
  await expect(page.getByRole('button',{name:'Iniciar simulación'})).toBeVisible();
  await nav(page,'Historial');
  await expect(page.locator('tbody tr')).toHaveCount(7);
  expect(errors).toEqual([]);
});
