import { test, expect } from '@playwright/test';

const password = 'PruebaLocal123';
async function register(page, skip = true) {
  await page.goto('/');
  await page.getByRole('button', {name:'Crear cuenta', exact:true}).click();
  await page.getByLabel('Nombre completo').fill('Ana Campos');
  await page.getByLabel('Correo electrónico', {exact:true}).fill('ana@example.com');
  await page.getByLabel('Iglesia o grupo musical', {exact:true}).fill('Grupo Esperanza');
  await page.getByLabel('Contraseña', {exact:true}).fill(password);
  await page.getByLabel('Confirmar contraseña', {exact:true}).fill(password);
  await page.getByRole('checkbox').check();
  await page.getByRole('button', {name:'Crear cuenta', exact:true}).click();
  await expect(page.getByRole('heading', {name:'Conozcamos tu espacio'})).toBeVisible();
  if(skip) await page.getByRole('button', {name:'Omitir por ahora y entrar al panel'}).click();
}
async function nav(page, name) {
  const toggle = page.getByRole('button', {name:'Abrir navegación'});
  if(await toggle.isVisible()) await toggle.click();
  await page.getByRole('navigation').getByRole('button', {name, exact:true}).click();
}
